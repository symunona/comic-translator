// node bench/free/smoke-mode.mjs <cdp> <app-url> <image> <lang> <shots-dir>: engine toggle on home and header, switch while waiting, upgrade offer
import { chromium } from "playwright-core";
const [cdp, app, img, lang, shots] = process.argv.slice(2);
const b = await chromium.connectOverCDP(cdp);
const p = await b.contexts()[0].newPage();
p.on("pageerror", (e) => console.log("pageerror:", e.message));
await p.setViewportSize({ width: 1400, height: 1000 });
await p.goto(app);
await p.evaluate(() => localStorage.clear());
await p.goto(app);
console.log("home:", await p.locator(".mode-row").innerText());
await p.click(".mode-row button:has-text('Free')");
console.log("home free:", await p.locator(".mode-row").innerText(), await p.evaluate(() => localStorage.getItem("ct.sotaRead")));
await p.click(".mode-row button:has-text('OpenRouter')");
await p.screenshot({ path: `${shots}/5-home.png` });
const [chooser] = await Promise.all([p.waitForEvent("filechooser"), p.evaluate(() => document.querySelector("input[type=file]").click())]);
await chooser.setFiles(img);
await p.waitForURL(/\/s\//);
await p.goto(p.url().replace(/lang=[^&]*/, `lang=${lang}`));
await p.waitForSelector(".dialog", { timeout: 120000 });
console.log("openrouter without key → dialog, chooser:", await p.locator(".path-choice").count());
await p.click(".topbar .mode-toggle button:has-text('Free')");
await p.waitForFunction(() => !!document.querySelector(".card textarea") && ![...document.querySelectorAll(".checklist li")].some((l) => l.classList.contains("running")), null, { timeout: 600000 });
console.log("switched to free → done:", JSON.stringify(await p.inputValue(".card textarea")));
console.log("offer:", await p.locator(".upgrade").innerText());
await p.screenshot({ path: `${shots}/6-offer.png` });
await p.click(".upgrade button");
await p.waitForSelector(".dialog input[type=password]", { state: "visible", timeout: 60000 });
console.log("offer → key form, chooser:", await p.locator(".path-choice").count(), "· shared stage:", await p.locator(".checklist li:nth-child(4) .step-msg").innerText().catch(() => "?"));
await p.close();
await b.close();
