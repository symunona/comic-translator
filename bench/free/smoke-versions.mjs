// node bench/free/smoke-versions.mjs <cdp> <app-url> <image> <lang> <shots-dir>: demo strip, new free version, version picker, Google per bubble
import { chromium } from "playwright-core";
const [cdp, app, img, lang, shots] = process.argv.slice(2);
const b = await chromium.connectOverCDP(cdp);
const p = await b.contexts()[0].newPage();
p.on("pageerror", (e) => console.log("pageerror:", e.message));
await p.setViewportSize({ width: 1400, height: 1000 });
await p.goto(app);
await p.evaluate(() => localStorage.clear());
await p.goto(app);
const [chooser] = await Promise.all([p.waitForEvent("filechooser"), p.evaluate(() => document.querySelector("input[type=file]").click())]);
await chooser.setFiles(img);
await p.waitForURL(/\/s\//);
await p.goto(p.url().replace(/lang=[^&]*/, `lang=${lang}`));
const idle = () => p.waitForFunction(() => !!document.querySelector(".card textarea") && ![...document.querySelectorAll(".checklist li")].some((l) => l.classList.contains("running")), null, { timeout: 600000 });
await idle();
const first = await p.inputValue(".card textarea");
console.log("loaded, bubble 1:", JSON.stringify(first));
await p.click(".pipeline-toggle");
console.log("opts:", await p.locator(".pipeline-opts").innerText());
await p.screenshot({ path: `${shots}/1-pipeline.png` });
await p.click("text=New version");
await p.waitForSelector(".free-box button", { timeout: 30000 });
console.log("key dialog shown (no key), picking free");
await p.click(".free-box button");
await p.waitForFunction(() => document.querySelector(".versions select"), null, { timeout: 600000 });
await idle();
console.log("stages:", await p.locator(".checklist").innerText().then((t) => t.replace(/\n+/g, " | ").slice(0, 600)));
console.log("versions:", await p.$$eval(".versions option", (os) => os.map((o) => o.textContent)));
const second = await p.inputValue(".card textarea");
console.log("new bubble 1:", JSON.stringify(second));
await p.selectOption(".versions select", "0");
await p.waitForTimeout(500);
console.log("after pick old:", JSON.stringify(await p.inputValue(".card textarea")), await p.$$eval(".versions option", (os) => os.map((o) => o.textContent)));
await p.click(".card .card-actions button:has-text('Google')");
await p.waitForSelector(".suggest:not(:has(.spinner))", { timeout: 30000 });
console.log("google:", await p.locator(".suggest").first().innerText());
await p.screenshot({ path: `${shots}/2-google.png` });
await p.click(".suggest button:has-text('use')");
console.log("after use:", JSON.stringify(await p.inputValue(".card textarea")));
await p.close();
await b.close();
