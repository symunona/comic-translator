// node bench/free/smoke-rerun.mjs <cdp> <app-url> <image> <lang> <shots-dir>: per-step engine dropdowns, rerun, edit warning
import { chromium } from "playwright-core";
const [cdp, app, img, lang, shots] = process.argv.slice(2);
const b = await chromium.connectOverCDP(cdp);
const p = await b.contexts()[0].newPage();
p.on("pageerror", (e) => console.log("pageerror:", e.message));
let accept = false;
p.on("dialog", (d) => {
  console.log("confirm:", d.message(), accept ? "→ accept" : "→ cancel");
  accept ? d.accept() : d.dismiss();
});
await p.setViewportSize({ width: 1400, height: 1000 });
await p.goto(app);
await p.evaluate(() => localStorage.clear());
await p.goto(app);
await p.click(".mode-row button:has-text('Free')");
const [chooser] = await Promise.all([p.waitForEvent("filechooser"), p.evaluate(() => document.querySelector("input[type=file]").click())]);
await chooser.setFiles(img);
await p.waitForURL(/\/s\//);
await p.goto(p.url().replace(/lang=[^&]*/, `lang=${lang}`));
const idle = () => p.waitForFunction(() => !!document.querySelector(".card textarea") && ![...document.querySelectorAll(".checklist li")].some((l) => l.classList.contains("running")), null, { timeout: 600000 });
await idle();
await p.fill(".card textarea", "MY HAND EDIT");
await p.waitForTimeout(800);
await p.click(".pipeline-toggle");
const sel = (step) => p.locator(".checklist li").nth({ ocr: 4, scene: 5, translate: 6, review: 7 }[step]).locator(".step-engine select");
await sel("translate").focus();
await p.waitForTimeout(2500);
console.log("engines:", await p.$$eval(".step-engine select", (ss) => ss.map((s) => s.value)), "· options:", await sel("translate").locator("option").count());
await p.locator(".checklist li").nth(6).locator("button:has-text('rerun')").click();
await p.waitForTimeout(500);
console.log("after cancel:", JSON.stringify(await p.inputValue(".card textarea")));
accept = true;
await p.locator(".checklist li").nth(6).locator("button:has-text('rerun')").click();
await p.waitForTimeout(1000);
await idle();
console.log("after rerun:", JSON.stringify(await p.inputValue(".card textarea")), "· versions:", await p.$$eval(".versions option", (os) => os.map((o) => o.textContent)));
await sel("review").selectOption("recommended");
await p.locator(".checklist li").nth(7).locator("button:has-text('rerun')").click();
await p.waitForSelector(".dialog", { timeout: 60000 });
console.log("review on recommended, no key → dialog:", (await p.locator(".dialog h3").innerText()), "· stages:", await p.$$eval(".checklist li", (ls) => ls.slice(4).map((l) => l.className.replace("step ", "") + ":" + (l.querySelector(".step-msg")?.textContent ?? ""))));
await p.screenshot({ path: `${shots}/7-rerun.png` });
await p.keyboard.press("Escape");
await p.click(".dialog .x").catch(() => {});
await p.screenshot({ path: `${shots}/8-pipeline.png` });
await p.setViewportSize({ width: 390, height: 844 });
await p.waitForTimeout(500);
await p.screenshot({ path: `${shots}/9-mobile.png` });
console.log("mobile overflow:", await p.evaluate(() => document.documentElement.scrollWidth));
await p.close();
await b.close();
