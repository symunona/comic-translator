// node bench/free/e2e-share.mjs <cdp> <app-url> <image> <lang>: free run with sharing on, one edit, count hub versions
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { chromium } from "playwright-core";
const [cdp, app, img, lang] = process.argv.slice(2);
const hash = createHash("sha256").update(readFileSync(img)).digest("hex");
const b = await chromium.connectOverCDP(cdp);
const p = await b.contexts()[0].newPage();
await p.setViewportSize({ width: 1400, height: 1000 });
await p.goto(app);
await p.evaluate(() => localStorage.clear());
await p.goto(app);
const [chooser] = await Promise.all([p.waitForEvent("filechooser"), p.evaluate(() => document.querySelector("input[type=file]").click())]);
await chooser.setFiles(img);
await p.waitForURL(/\/s\//);
await p.goto(p.url().replace(/lang=[^&]*/, `lang=${lang}`));
await p.waitForSelector(".free-box button", { timeout: 120000 });
await p.waitForSelector("text=Verified, sharing is on.", { timeout: 60000 });
console.log("turnstile verified");
await p.click(".free-box button");
await p.waitForFunction(() => !!document.querySelector(".card textarea") && ![...document.querySelectorAll(".checklist li")].some((l) => l.classList.contains("running")), null, { timeout: 300000 });
const status = () => p.evaluate(() => [...document.querySelectorAll(".key-ok, .muted, .fatal")].map((e) => e.textContent.trim()).filter((t) => /shar/i.test(t)).join(" | "));
const versions = () => p.evaluate(async (h) => {
  const s = JSON.parse(localStorage.getItem("ct.session") ?? "null");
  const r = await fetch(`/api/comics/${h}`, { headers: { "X-Session": s?.token ?? "" } });
  return (await r.json()).translations.map((t) => `${t.id}:${t.lang}`).join(",");
}, hash);
await p.waitForTimeout(3000);
console.log("after run:", await status(), "· hub:", await versions());
const t0 = Date.now();
await p.fill(".card textarea", "EDITED BY THE AUTO-PUBLISH TEST");
await p.waitForTimeout(1500);
console.log("after edit:", await status());
await p.waitForFunction(() => document.body.textContent.includes("Shared with others"), null, { timeout: 90000, polling: 1000 });
console.log(`shared again after ${((Date.now() - t0) / 1000).toFixed(0)} s:`, await status(), "· hub:", await versions());
await p.fill(".card textarea", "SECOND EDIT");
await p.waitForTimeout(1500);
console.log("2nd edit:", await status());
const t1 = Date.now();
await p.waitForFunction(() => document.body.textContent.includes("Shared with others"), null, { timeout: 120000, polling: 1000 });
console.log(`shared again after ${((Date.now() - t1) / 1000).toFixed(0)} s (gap rule):`, "· hub:", await versions());
await p.close();
await b.close();
